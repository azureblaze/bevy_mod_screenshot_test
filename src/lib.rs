/// Configures how the test behaves. Apply with [TestTasks::with_config].
#[derive(Resource, Clone)]
pub struct ScreenshotTestConfig {
    /// The directory to place the expected ("golden") screenshot.
    ///
    /// Defaults to `{CARGO_MANIFEST_DIR}/tests/expected`
    pub expected_dir: PathBuf,

    /// The directory the app will write screenshots generated by the test to. This directory should
    /// be ignored in VCS.
    ///
    /// Defaults to `{CARGO_MANIFEST_DIR}/tests/actual`
    pub actual_dir: PathBuf,

    /// The directory to write the screenshot diff if the expected and actual image does not match.
    /// This directory should be ignored in VCS.
    ///
    /// Defaults to `{CARGO_MANIFEST_DIR}/tests/diff`
    pub diff_dir: PathBuf,

    /// How much difference in the actual output is considered acceptable. Due to floating point
    /// errors, the actual image is unlikely to completely match even without any code change.
    ///
    /// Defaults to allowing 5% of pixels to be completely different, and the rest can be off by 1.
    pub threshold: RatioThreshold,
}

#[derive(Clone)]
pub struct RatioThreshold(Vec<RatioThresholdEntry>);

#[derive(Clone, Debug)]
pub struct RatioThresholdEntry {
    /// Allowable difference in the pixel's value, as the [luma](https://en.wikipedia.org/wiki/Luma_(video))
    /// of abs(expected.rgb - actual.rgb).
    max_magnitude: u8,
    /// Max ratio of the pixels that is allowed to have difference up to `max_magnitude`, expressed
    /// as a value in `[0.0, 1.0]`
    max_ratio: f32,
}

impl RatioThreshold {
    pub fn new(data: impl IntoIterator<Item = RatioThresholdEntry>) -> Self {
        Self(
            data.into_iter()
                .map(|entry| {
                    assert!(
                        entry.max_magnitude > 0,
                        "putting 0 magnitude ({entry:?}) in RatioThreshold is redundant"
                    );
                    entry
                })
                .collect(),
        )
    }

    /// Allow any pixels that does not have a difference greater than `magnitude`
    #[must_use]
    pub fn no_bigger_than(magnitude: u8) -> Self {
        if magnitude == 0 {
            Self::new([])
        } else {
            Self::new([RatioThresholdEntry {
                max_magnitude: magnitude,
                max_ratio: 1.0,
            }])
        }
    }

    fn to_threshold(&self, image: &ImgVec<[u8; 4]>) -> Threshold {
        let size = image.width() * image.height();
        Threshold::new(
            self.0
                .iter()
                .map(|entry| {
                    (
                        entry.max_magnitude.clone(),
                        (size as f32 * entry.max_ratio) as usize,
                    )
                })
                .filter(|(magnitude, _)| magnitude.to_owned() > 0),
        )
    }
}

impl ScreenshotTestConfig {
    fn expected(&self, name: &str) -> PathBuf {
        self.expected_dir.join(format!("{name}.png"))
    }
    fn actual(&self, name: &str) -> PathBuf {
        self.actual_dir.join(format!("{name}.png"))
    }
    fn diff(&self, name: &str) -> PathBuf {
        self.diff_dir.join(format!("{name}.png"))
    }
}

impl Default for ScreenshotTestConfig {
    fn default() -> Self {
        let root = Path::new(&std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("tests");
        ScreenshotTestConfig {
            expected_dir: root.join("expected"),
            actual_dir: root.join("actual"),
            diff_dir: root.join("diff"),
            threshold: RatioThreshold::new([
                RatioThresholdEntry {
                    max_magnitude: 255,
                    max_ratio: 0.05,
                },
                RatioThresholdEntry {
                    max_magnitude: 1,
                    max_ratio: 1.0,
                },
            ]),
        }
    }
}

#[derive(Default, Clone)]
pub struct TaskInfo {
    pub name: String,
    pub screenshot: String,
}

#[derive(Default)]
pub struct ScreenshotTestPlugin;

impl Plugin for ScreenshotTestPlugin {
    fn build(&self, app: &mut App) {
        app.add_plugins(PipelinesReadyPlugin)
            .add_systems(Update, run_task.run_if(should_run_next_task));
    }
}
/// Defines a sequential list of tasks to run, including [Self::take_screenshot]. [Self::validate]
/// will then run the bevy app with the tasks, and test the screenshots taken matches expected
/// images.
///
/// The test should be marked with `harness = false` in the `Cargo.toml` and implement `main()`, as
/// Bevy cannot run under the default rust test harness.
///
/// # Example
/// ```ignore
/// fn main() {
///     let mut app = App::new();
///     app.add_plugins(DefaultPlugins)
///         .add_plugins(ScreenshotTestPlugin);
///
///     TestTasks::for_app(&mut app)
///         .with_config(ScreenshotTestConfig{..default()})
///         .run("do things", |mut task: ResMut<TestTask>| {
///             info!("doing... nothing!");
///             task.finish();
///         })
///         .take_screenshot("sc1")
///         .validate();
/// }
/// ```
pub struct TestTasks<'a> {
    app: &'a mut App,
    tasks: VecDeque<(usize, TaskInfo)>,
    config: ScreenshotTestConfig,
}

impl TestTasks<'_> {
    #[must_use]
    pub fn for_app(app: &mut App) -> TestTasks<'_> {
        TestTasks {
            app,
            tasks: VecDeque::default(),
            config: ScreenshotTestConfig::default(),
        }
    }
    #[must_use]
    pub fn with_config(&mut self, config: ScreenshotTestConfig) -> &mut Self {
        self.config = config;
        self
    }

    /// run the system with custom [TaskInfo].
    #[must_use]
    pub fn run_raw<M>(
        &mut self,
        task_info: TaskInfo,
        task: impl IntoScheduleConfigs<ScheduleSystem, M>,
    ) -> &mut Self {
        let task_id = self.tasks.len();

        self.app.add_systems(
            Update,
            task.after(run_task)
                .run_if(current_task(task_id).and_then(run_once)),
        );

        self.tasks.push_back((task_id, task_info));
        self
    }

    #[must_use]
    pub fn run_unnamed<M>(
        &mut self,
        task: impl IntoScheduleConfigs<ScheduleSystem, M>,
    ) -> &mut Self {
        self.run_raw(TaskInfo::default(), task)
    }

    /// runs a custom system once when the previous action has finished. The system must eventually
    /// call [TestTask::finish()] from `ResMut<TestTask>`, directly or indirectly, or the test will
    /// not progress.
    #[must_use]
    pub fn run<M>(
        &mut self,
        name: &str,
        task: impl IntoScheduleConfigs<ScheduleSystem, M>,
    ) -> &mut Self {
        self.run_raw(
            TaskInfo {
                name: name.to_owned(),
                ..default()
            },
            task,
        )
    }

    /// Take a screenshot and compare it with the expected image. The screenshot is saved to [ScreenshotTestConfig.actual_dir](ScreenshotTestConfig#structfield.actual_dir)
    #[must_use]
    pub fn take_screenshot(&mut self, name: &str) -> &mut Self {
        self.run_raw(
            TaskInfo {
                name: format!("take screenshot '{}'", name),
                screenshot: name.to_owned(),
            },
            noop(),
        )
    }

    /// Wait until the [condition](SystemCondition) passes.
    #[must_use]
    pub fn wait_until<M>(&mut self, name: &str, condition: impl SystemCondition<M>) -> &mut Self {
        let task_info = TaskInfo {
            name: name.to_owned(),
            ..default()
        };

        let task_id = self.tasks.len();

        self.app.add_systems(
            Update,
            noop()
                .after(run_task)
                .run_if(current_task(task_id).and_then(condition).and_then(run_once)),
        );

        self.tasks.push_back((task_id, task_info));
        self
    }

    /// Wait until all assets has been loaded.
    ///
    /// WARNING: currently only works for pipelines. Use [Self::sleep] to guess when all loading is
    /// completed.
    #[must_use]
    pub fn await_assets(&mut self) -> &mut Self {
        self.wait_until("await assets loaded", assets_loaded)
    }

    /// skip a single frame
    #[must_use]
    pub fn noop(&mut self) -> &mut Self {
        self.run("noop", noop())
    }

    /// Skip frames.
    #[must_use]
    pub fn sleep(&mut self, frames: u32) -> &mut Self {
        self.run(
            &format!("set sleep target +{frames} frames"),
            move |mut task: ResMut<TestTask>, frame_count: Res<FrameCount>| {
                task.sleep_target = frame_count.0 + frames;
                task.finish();
            },
        )
        .wait_until(&format!("sleep {frames} frames"), sleep_done)
    }

    /// Run the app with all tasks and compare the screenshot.
    pub fn validate(&mut self) {
        for (_, task) in &self.tasks {
            if !task.screenshot.is_empty() {
                let file = self.config.actual(&task.screenshot);
                if file.exists() {
                    info!("cleaning {}", file.to_str().unwrap());
                    fs::remove_file(file).unwrap();
                }
            }
        }

        let state = TestTask {
            tasks: self.tasks.clone(),
            ..default()
        };

        self.app
            .insert_resource(state)
            .insert_resource(self.config.clone());

        self.app.run();
        self.validate_impl();
    }

    fn validate_impl(&self) {
        let mut failed = false;

        let red = anstyle::Style::new().fg_color(Some(AnsiColor::Red.into()));
        let yellow = anstyle::Style::new().fg_color(Some(AnsiColor::Yellow.into()));
        let green = anstyle::Style::new().fg_color(Some(AnsiColor::Green.into()));

        for (_, task) in &self.tasks {
            if task.screenshot.is_empty() {
                continue;
            }

            let actual = self.config.actual(&task.screenshot);
            if !actual.exists() {
                println!(
                    "[{red}FAIL{red:#}] screenshot '{}' not taken.",
                    task.screenshot
                );
                failed = true;
                continue;
            }

            let expected = self.config.expected(&task.screenshot);
            if !expected.exists() {
                fs::create_dir_all(expected.parent().unwrap()).unwrap();
                fs::copy(actual, expected).unwrap();
                println!(
                    "[{yellow}NEW {yellow:#}] created expected screenshot '{}' from actual.",
                    task.screenshot
                );
                continue;
            }

            let actual = from_rgba(image::open(actual).unwrap().to_rgba8());
            let expected = from_rgba(image::open(expected).unwrap().to_rgba8());

            let difference = rendiff::diff(actual.as_ref(), expected.as_ref());
            if !self
                .config
                .threshold
                .to_threshold(&actual)
                .allows(difference.histogram())
            {
                let Some(diff_image) = difference.diff_image() else {
                    panic!()
                };
                let diff = self.config.diff(&task.screenshot);
                fs::create_dir_all(diff.parent().unwrap()).unwrap_or(());
                image::RgbaImage::from_raw(
                    diff_image.width() as u32,
                    diff_image.height() as u32,
                    Vec::from(diff_image.buf().as_flattened()),
                )
                .unwrap()
                .save(diff.clone())
                .unwrap();

                failed = true;
                println!(
                    "[{red}FAIL{red:#}] screenshot '{}' mismatch: file://{}",
                    task.screenshot,
                    diff.to_str().unwrap()
                );
                continue;
            }
            println!("[{green}PASS{green:#}] screenshot '{}'", task.screenshot);
        }

        if failed {
            std::process::exit(1);
        } else {
            std::process::exit(0);
        }
    }
}

fn from_rgba(image: image::RgbaImage) -> imgref::ImgVec<[u8; 4]> {
    // These conversions cannot fail because if they didn't fit in `usize`,
    // the `buf` couldn't exist in memory.
    let width = usize::try_from(image.width()).expect("width too large");
    let height = usize::try_from(image.height()).expect("height too large");

    let buf = image
        .into_vec()
        .chunks(4)
        .map(|pixel| <[u8; 4]>::try_from(pixel).unwrap())
        .collect();

    imgref::ImgVec::new(buf, width, height)
}

fn noop() -> impl FnMut(ResMut<TestTask>) {
    move |mut task| task.finish()
}

fn current_task(id: usize) -> impl FnMut(Res<TestTask>) -> bool {
    move |state| state.current_task_id().eq(&Some(id))
}

fn assets_loaded(pipelines_ready: Res<PipelinesReady>) -> bool {
    pipelines_ready.0
}

fn sleep_done(task: Res<TestTask>, frame: Res<FrameCount>) -> bool {
    frame.0 > task.sleep_target
}

fn should_run_next_task(test: Res<TestTask>) -> bool {
    if !test.current_task_finished {
        return false;
    }
    if test.screenshot_pending {
        return test.screenshot_finished;
    }
    true
}

/// [Resource] that controls the task flow. [Self::finish] should be called when the current task
/// and its async operations has been completed.
#[derive(Resource, Default)]
pub struct TestTask {
    tasks: VecDeque<(usize, TaskInfo)>,
    current_task_finished: bool,
    screenshot_pending: bool,
    screenshot_finished: bool,
    sleep_target: u32,
}

impl TestTask {
    /// Finish the current task and start the next one. If there are no tasks left the bevy app
    /// will be terminated, and the screenshots will be validated.
    pub fn finish(&mut self) {
        self.current_task_finished = true;
    }

    fn current_task_id(&self) -> Option<usize> {
        self.tasks.front().map(|info| info.0)
    }

    fn reset_current_task_state(&mut self) {
        self.screenshot_finished = false;
        self.screenshot_pending = false;
        self.current_task_finished = false;
    }
}

fn run_task(
    mut commands: Commands,
    mut state: ResMut<TestTask>,
    config: Res<ScreenshotTestConfig>,
) {
    if let Some((_, task)) = state.tasks.front() {
        if !task.screenshot.is_empty() && !state.screenshot_pending {
            commands
                .spawn(Screenshot::primary_window())
                .observe(save_sc(
                    config.actual_dir.join(format!("{}.png", task.screenshot)),
                ));
            state.screenshot_pending = true;
            return;
        }
    }

    let Some(task) = state.tasks.pop_front() else {
        info!("No tasks added");
        commands.write_message(AppExit::Success);
        return;
    };
    info!("Finished task {}: {}", task.0, task.1.name);
    state.reset_current_task_state();

    if state.tasks.is_empty() {
        info!("end of tasks");
        commands.write_message(AppExit::Success);
        return;
    }
}

fn save_sc(path: impl AsRef<Path>) -> impl FnMut(On<ScreenshotCaptured>, ResMut<TestTask>) {
    let path = path.as_ref().to_owned();
    fs::create_dir_all(path.clone().parent().unwrap()).unwrap_or(());
    fs::remove_file(path.clone()).unwrap_or(());
    move |screenshot_captured, mut task: ResMut<TestTask>| {
        save_to_disk(path.clone())(screenshot_captured);
        task.screenshot_finished = true;
    }
}

mod pipelines_ready {
    use bevy::app::{App, Plugin};
    use bevy::prelude::{Res, ResMut, Resource};
    use bevy::render::render_resource::PipelineCache;
    use bevy::render::{ExtractSchedule, MainWorld, RenderApp};

    pub struct PipelinesReadyPlugin;
    impl Plugin for PipelinesReadyPlugin {
        fn build(&self, app: &mut App) {
            app.insert_resource(PipelinesReady::default());

            // In order to gain access to the pipelines status, we have to
            // go into the `RenderApp`, grab the resource from the main App
            // and then update the pipelines status from there.
            // Writing between these Apps can only be done through the
            // `ExtractSchedule`.
            app.sub_app_mut(RenderApp)
                .add_systems(ExtractSchedule, update_pipelines_ready);
        }
    }

    #[derive(Resource, Debug, Default)]
    pub struct PipelinesReady(pub bool);

    fn update_pipelines_ready(mut main_world: ResMut<MainWorld>, pipelines: Res<PipelineCache>) {
        if let Some(mut pipelines_ready) = main_world.get_resource_mut::<PipelinesReady>() {
            pipelines_ready.0 = pipelines.waiting_pipelines().count() == 0;
        }
    }
}
